"""Apply the model-selection rules to ml/results/benchmark.json (real checkpoints only) -> ml/results/selection.md/json.

SERVER model (amended rule, post hoc; docs/decisions.md Day 1.9):
  among int8 models with p50 natural-length CPU latency < 50 ms (2 threads),
  keep those with indirect_val recall >= 0.80 and indirect_val FPR <= 0.05 (at the int8 model's val-tuned threshold);
  the highest val F1 wins. If nobody passes the indirect gate, fall back to the original rule and say so.
ORIGINAL rule (pre-registered in CLAUDE.md), always reported next to the amended pick:
  highest val F1 among int8 models with p50 natural latency < 50 ms.
BROWSER pre-check model: among int8 models with int8 size <= 30 MB, same indirect_val gate, highest val F1.
  (CLAUDE.md says "most accurate under ~30 MB"; applying the same indirect gate is my extension, logged in the session log.)
  Fallback if nothing qualifies: word+char TF-IDF exported with skl2onnx.
indirect_test, test, tricky and xstest are shown for context and never used to select.

Run (repo root): python ml/select_models.py
"""
import json
from pathlib import Path

RESULTS = Path(__file__).parent / "results"
LAT_MS, SIZE_MB, MIN_RECALL, MAX_FPR = 50.0, 30.0, 0.80, 0.05


def rows(bench, include_standin=False):
    out = []
    for key, r in bench.items():
        if key == "env" or (r.get("standin") and not include_standin) or r.get("status") != "ok":
            continue
        a, lat = r["int8"]["accuracy"], r["int8"]["latency"]
        at = a["at_val_threshold"]
        out.append({
            "job": r["job"], "int8_mb": r["int8"]["size_mb"], "fp32_mb": r["fp32"]["size_mb"],
            "p50_ms": lat["natural"]["p50_ms"], "p95_ms": lat["natural"]["p95_ms"], "p50_512_ms": lat["len512"]["p50_ms"],
            "val_f1": a["val_f1"], "thr": a["threshold_val_tuned"],
            "iv_recall": at["indirect_val"]["recall"], "iv_fpr": at["indirect_val"]["fpr"],
            "it_recall": at["indirect_test"]["recall"], "it_fpr": at["indirect_test"]["fpr"],
            "test_f1": at["test"]["f1"], "test_fpr": at["test"]["fpr"], "tricky": at["tricky"]["_overall"]["correct"],
            "hidden": at["tricky"]["hidden_injection_document"]["correct"], "xstest_fp": at["xstest_fp"],
            "fp32_val_f1": r["fp32"]["accuracy"]["val_f1"],
        })
    return out


def main():
    import argparse
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--smoke", action="store_true", help="code-path test on ml/cache/bench_smoke.json (stand-ins); writes to ml/cache only")
    args = ap.parse_args()
    global RESULTS
    src = Path(__file__).parent / "cache" / "bench_smoke.json" if args.smoke else RESULTS / "benchmark.json"
    bench = json.loads(src.read_text())
    R = rows(bench, include_standin=args.smoke)
    if args.smoke:
        RESULTS = Path(__file__).parent / "cache"
    if not R:
        raise SystemExit("no real-checkpoint results in benchmark.json (stand-ins are never used for selection); "
                         "run: python ml/export_quantize.py --all-real && python ml/benchmark.py --all-real")
    # The 50 ms gate is evaluated on one sample of 300 val prompts; ml/window_eval.py re-measured the same int8 models over ALL val prompts.
    # If the two disagree about the gate, the gate result is not robust and is reported as INCONCLUSIVE (review finding, 2026-11-15).
    we_path = RESULTS / "window_eval.json"
    we = json.loads(we_path.read_text()) if we_path.exists() else {}
    for r in R:
        r["p50_alt"] = next((x["lat_p50"] for x in we.get(r["job"], []) if x.get("W") == 512), None)
        r["fast"] = r["p50_ms"] < LAT_MS
        r["latency_inconclusive"] = bool(r["fast"] and r["p50_alt"] is not None and r["p50_alt"] >= LAT_MS)
        r["indirect_ok"] = r["iv_recall"] >= MIN_RECALL and r["iv_fpr"] <= MAX_FPR
        r["small"] = r["int8_mb"] <= SIZE_MB
    best = lambda c: max(c, key=lambda r: r["val_f1"]) if c else None
    original = best([r for r in R if r["fast"]])
    amended_pool = [r for r in R if r["fast"] and r["indirect_ok"]]
    server = best(amended_pool)
    server_note = "amended rule"
    if server is None:
        server, server_note = original, "NO model passed the indirect gate; fell back to the original rule"
    browser_pool = [r for r in R if r["small"] and r["indirect_ok"]]
    browser = best(browser_pool)
    browser_note = "val F1 under the size cap, with the indirect gate"
    if browser is None:
        browser, browser_note = best([r for r in R if r["small"]]), "NO small model passed the indirect gate; best val F1 under the size cap (or use the TF-IDF fallback)"

    L = ["# Model selection (generated by ml/select_models.py)\n",
         f"int8 models, CPU, batch 1, 2 threads. Gates: p50 natural-length latency < {LAT_MS:.0f} ms; indirect_val recall >= {MIN_RECALL} and FPR <= {MAX_FPR} "
         f"at the val-tuned threshold; browser size <= {SIZE_MB:.0f} MB. Val F1 decides among those that pass.\n",
         "| model | int8 MB | p50 ms (p95) | 512-tok p50 | val F1 | thr | indirect_val recall / FPR | latency ok | indirect gate | size ok | "
         "indirect_test recall / FPR | test F1 / FPR | tricky /49 (hidden /5) | xstest FP |", "|" + "---|" * 14]
    for r in sorted(R, key=lambda r: -r["val_f1"]):
        L.append(f"| {r['job']} | {r['int8_mb']} | {r['p50_ms']:.1f} ({r['p95_ms']:.1f}) | {r['p50_512_ms']:.1f} | {r['val_f1']:.3f} | {r['thr']:.3f} | "
                 f"{r['iv_recall']:.3f} / {r['iv_fpr']:.3f} | {('INCONCLUSIVE (%.1f vs %.1f ms)' % (r['p50_ms'], r['p50_alt'])) if r['latency_inconclusive'] else ('yes' if r['fast'] else 'NO')} | {'pass' if r['indirect_ok'] else 'FAIL'} | "
                 f"{'yes' if r['small'] else 'no'} | {r['it_recall']:.3f} / {r['it_fpr']:.3f} | {r['test_f1']:.3f} / {r['test_fpr']:.3f} | "
                 f"{r['tricky']} ({r['hidden']}) | {r['xstest_fp']} |")
    L += ["", f"**Server model: {server['job']}** ({server_note}); val F1 {server['val_f1']:.3f}, p50 {server['p50_ms']:.1f} ms, int8 {server['int8_mb']} MB.",
          f"Original (pre-registered) rule would pick: **{original['job'] if original else 'nobody (no model under the latency limit)'}**."
          + ("  Same model." if original and original['job'] == server['job'] else "  Different from the amended pick."),
          f"**Browser pre-check model: {browser['job'] if browser else 'none -> use the TF-IDF skl2onnx fallback'}** ({browser_note})."]
    if server and server.get("latency_inconclusive"):
        L.append(f"\n**Caveat: the server model's latency gate is INCONCLUSIVE.** p50 {server['p50_ms']:.1f} ms on 300 random val prompts, "
                 f"{server['p50_alt']:.1f} ms when the same model was re-measured on all val prompts (limit {LAT_MS:.0f} ms): the pass depends on the sample. "
                 "Measure on the deployment hardware before relying on it.")
    (RESULTS / "selection.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (RESULTS / "selection.json").write_text(json.dumps({"server": server, "server_note": server_note, "original_rule_pick": original,
                                                         "browser": browser, "browser_note": browser_note, "all": R}, indent=2))
    print("\n".join(L))


if __name__ == "__main__":
    main()
