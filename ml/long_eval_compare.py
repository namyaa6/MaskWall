"""Head+tail vs sliding-window scanning on the long-document eval set (docs/decisions.md Day 2.1).

Evaluates the SHIPPING scanner code (backend/app/scanners/injection.py) for the packaged model(s) in backend/model/<name>/:
  head_tail : one 510-token window (first 256 + last 254 tokens)
  sliding   : overlapping 510-token windows, stride 255, max score, window cap = 6 (the API default)
Thresholds come from the model's own val tuning (model_meta.json): block = max(thr_f1, thr_fpr1pct), warn = min(...).
Reports recall by injection position (start / middle / end), FPR on benign long documents, F1, windows per document and latency.
Usage (repo root): python ml/long_eval_compare.py minilm [deberta]   -> ml/results/long_eval_compare.json and .md
"""
import json
import math
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.scanners.injection import InjectionScanner  # noqa: E402

RESULTS = ROOT / "ml" / "results"
DATA = ROOT / "ml" / "data" / "processed" / "long_eval.parquet"
MODES = [("head_tail", {}), ("sliding", {"max_windows": 6})]


def wilson(k, n, z=1.96):
    if n == 0:
        return [0.0, 0.0]
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return [round((c - h) / d, 3), round((c + h) / d, 3)]


def rate(flags):
    flags = list(flags)
    return {"k": int(sum(flags)), "n": len(flags), "rate": round(sum(flags) / max(len(flags), 1), 3), "ci95": wilson(sum(flags), len(flags))}


def run(name, df):
    out = {}
    for mode, kw in MODES:
        sc = InjectionScanner.load(ROOT / "backend" / "model" / name, mode=mode, threads=2, **kw)
        block, warn = max(sc.thr_f1, sc.thr_fpr1pct), min(sc.thr_f1, sc.thr_fpr1pct)
        sc.scan("warm up " * 20)
        recs = []
        for _, r in df.iterrows():
            s = sc.scan(r.text)
            recs.append({"score": s.score, "n_windows": s.n_windows, "coverage": s.coverage, "inf_ms": s.inference_ms,
                         "tok_ms": s.tokenize_ms, "win_ms": [w.ms for w in s.windows]})
        d = df.assign(**{k: [x[k] for x in recs] for k in ("score", "n_windows", "coverage", "inf_ms", "tok_ms")})
        att, ben = d[d.label == 1], d[d.label == 0]
        tp_block, fp_block = (att.score >= block).sum(), (ben.score >= block).sum()
        prec = tp_block / max(tp_block + fp_block, 1)
        rec = tp_block / len(att)
        res = {
            "thresholds": {"block": block, "warn": warn, "thr_f1": sc.thr_f1, "thr_fpr1pct": sc.thr_fpr1pct},
            "recall_at_block": {p: rate(att[att.position == p].score >= block) for p in ("start", "middle", "end")},
            "recall_at_block_all": rate(att.score >= block),
            "recall_at_warn_or_block": {p: rate(att[att.position == p].score >= warn) for p in ("start", "middle", "end")},
            "fpr_at_block": rate(ben.score >= block), "fpr_at_warn_or_block": rate(ben.score >= warn),
            "f1_at_block": round(2 * prec * rec / max(prec + rec, 1e-12), 3),
            "benign_fpr_at_block_by_windows_needed": {int(k): rate(g.score >= block) for k, g in ben.groupby("n_windows")},
            "median_score": {"attack": round(float(att.score.median()), 3), "benign": round(float(ben.score.median()), 3)},
            "coverage_full": int((d.coverage == "full").sum()), "coverage_partial": int((d.coverage == "partial").sum()),
            "windows_per_doc_mean": round(float(d.n_windows.mean()), 2),
            "latency_ms_per_doc": {"inference_p50": round(float(d.inf_ms.median()), 1), "inference_p95": round(float(d.inf_ms.quantile(0.95)), 1),
                                    "inference_max": round(float(d.inf_ms.max()), 1), "tokenize_p50": round(float(d.tok_ms.median()), 2)},
            "latency_ms_per_window_mean": round(float(np.mean([w for x in recs for w in x["win_ms"]])), 1),
        }
        out[mode] = res
        print(f"[{name}/{mode}] recall@block start/middle/end = " + " / ".join(f"{res['recall_at_block'][p]['rate']:.3f}" for p in ("start", "middle", "end"))
              + f"; benign FPR@block {res['fpr_at_block']['rate']:.3f}; per-doc p50 {res['latency_ms_per_doc']['inference_p50']} ms", flush=True)
    return out


def main():
    names = sys.argv[1:] or ["minilm"]
    df = pd.read_parquet(DATA)
    path = RESULTS / "long_eval_compare.json"
    report = json.loads(path.read_text()) if path.exists() else {}
    for name in names:
        report[name] = run(name, df)
        path.write_text(json.dumps(report, indent=2))
    L = ["# Long documents: head+tail vs sliding windows (generated by ml/long_eval_compare.py)\n",
         f"{(df.label == 1).sum()} attack documents (38 per position) and {(df.label == 0).sum()} benign documents, "
         f"{int(df.doc_chars.min())}-{int(df.doc_chars.max())} characters, {int(df.n_tokens.min())}-{int(df.n_tokens.max())} tokens. "
         "Rates are k/n with Wilson 95% intervals. block = max(thr_f1, thr_fpr1pct), warn = min(...) of the model's val tuning.\n",
         "| model | mode | recall start | recall middle | recall end | recall all | benign FPR at block | benign FPR at warn+ | F1 | windows/doc | p50 / p95 ms per doc | ms per window |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, modes in report.items():
        for mode, r in modes.items():
            f = lambda x: f"{x['k']}/{x['n']} [{x['ci95'][0]:.2f}, {x['ci95'][1]:.2f}]"
            L.append(f"| {name} | {mode} | " + " | ".join(f(r["recall_at_block"][p]) for p in ("start", "middle", "end")) + f" | {f(r['recall_at_block_all'])} | "
                     f"{f(r['fpr_at_block'])} | {f(r['fpr_at_warn_or_block'])} | {r['f1_at_block']} | {r['windows_per_doc_mean']} | "
                     f"{r['latency_ms_per_doc']['inference_p50']} / {r['latency_ms_per_doc']['inference_p95']} | {r['latency_ms_per_window_mean']} |")
    (RESULTS / "long_eval_compare.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", path)


if __name__ == "__main__":
    main()
