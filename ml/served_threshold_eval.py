"""Evaluate the int8 models at the thresholds the SERVER actually applies (found by the ml/ review: DeBERTa's earlier numbers were at its F1
threshold 0.277, while the policy blocks at 0.585).

Thresholds come from backend/model/<name>/model_meta.json (tuned on the main val set, head+tail scoring):
  block = max(thr_f1, thr_fpr1pct), warn = min(thr_f1, thr_fpr1pct); thr_f1 is also reported for reference.
For every threshold: val, test (F1/FPR/recall/precision with bootstrap CIs), indirect_val, indirect_test, tricky (overall and per category),
xstest false positives; and for the policy as a whole the three-way outcome (allow / warn / block) for benign and attack rows of test.
Reporting only: nothing here selects or tunes anything.

Run (repo root, after backend/scripts/prepare_model.py for both models): python ml/served_threshold_eval.py
Output: ml/results/served_thresholds.json and .md
"""
import json
import sys
from pathlib import Path

import numpy as np
from transformers import AutoTokenizer

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).parent))
import benchmark as bm  # noqa: E402
import export_quantize as eq  # noqa: E402
import train_baseline as tb  # noqa: E402

JOBS = {"minilm": "cleaned_aug/minilm", "deberta": "cleaned_aug/deberta_v3_small"}
RES = ROOT / "ml" / "results"


def at(sets, sc, thr, thr_fpr):
    yv = sets["val"]["label"].to_numpy()
    t = tb.evaluate_split(sets["test"], sc["test"], thr, thr_fpr)
    out = {"threshold": thr, "val": {k: tb.rates(yv, sc["val"] >= thr)[k] for k in ("f1", "fpr", "recall", "precision")},
           "test": {"f1": t["f1"], "fpr": t["fpr"], "recall": t["recall"], "precision": t["precision"], "ci95": t["ci95"],
                    "confusion_matrix": t["confusion_matrix"]}}
    for n in ("indirect_val", "indirect_test"):
        r = tb.rates(sets[n]["label"].to_numpy(), sc[n] >= thr)
        out[n] = {"recall": r["recall"], "fpr": r["fpr"], "confusion_matrix": r["confusion_matrix"]}
    tk = tb.evaluate_tricky(sets["tricky"], sc["tricky"], thr)
    out["tricky"] = {k: (v["correct"], v["total"]) for k, v in tk.items()}
    out["xstest_fp"] = int((sc["xstest_safe"] >= thr).sum())
    return out


def three_way(df, scores, warn, block):
    y = df["label"].to_numpy()
    res = {}
    for lab, name in ((0, "benign"), (1, "attack")):
        s = scores[y == lab]
        res[name] = {"n": int(len(s)), "allow": float((s < warn).mean()), "warn": float(((s >= warn) & (s < block)).mean()), "block": float((s >= block).mean())}
    return res


def main():
    sets = bm.load_sets()
    report = {}
    for name, job in JOBS.items():
        meta = json.loads((ROOT / "backend" / "model" / name / "model_meta.json").read_text())
        tok = AutoTokenizer.from_pretrained(str(eq.CKPT / job))
        sess = bm.session(eq.ONNX_DIR / job / "int8.onnx")
        print(f"[{name}] scoring {sum(len(d) for d in sets.values())} rows ...", flush=True)
        sc = {n: bm.scores(sess, tok, d["text"].tolist()) for n, d in sets.items()}
        f1, fpr1 = meta["thr_f1"], meta["thr_fpr1pct"]
        warn, block = min(f1, fpr1), max(f1, fpr1)
        report[name] = {"thr_f1": f1, "thr_fpr1pct": fpr1, "warn": warn, "block": block,
                        "at_block": at(sets, sc, block, fpr1), "at_warn": at(sets, sc, warn, fpr1), "at_f1": at(sets, sc, f1, fpr1),
                        "policy_three_way_test": three_way(sets["test"], sc["test"], warn, block),
                        "policy_three_way_indirect_test": three_way(sets["indirect_test"], sc["indirect_test"], warn, block)}
        b = report[name]["at_block"]
        print(f"[{name}] block {block:.3f}: test F1 {b['test']['f1']:.3f} FPR {b['test']['fpr']:.3f} recall {b['test']['recall']:.3f}; "
              f"indirect_test R {b['indirect_test']['recall']:.3f} FPR {b['indirect_test']['fpr']:.3f}; xstest FP {b['xstest_fp']}", flush=True)
        (RES / "served_thresholds.json").write_text(json.dumps(report, indent=2))

    L = ["# Metrics at the thresholds the server applies (generated by ml/served_threshold_eval.py)\n",
         "block = max(thr_f1, thr_fpr1pct), warn = min(...) from each model's val tuning. Reporting only. Test CIs: bootstrap 95%.\n",
         "| model | point | threshold | val F1 | test F1 [CI] | test FPR [CI] | test recall | test precision | indirect_val R / FPR | indirect_test R / FPR | tricky /49 (hidden /5) | xstest FP |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, r in report.items():
        for key, lab in (("at_warn", "warn"), ("at_block", "**block (served)**"), ("at_f1", "F1-opt (earlier reports)")):
            x = r[key]
            c = x["test"]["ci95"]
            L.append(f"| {name} | {lab} | {x['threshold']:.3f} | {x['val']['f1']:.3f} | {x['test']['f1']:.3f} [{c['f1'][0]:.3f}, {c['f1'][1]:.3f}] | "
                     f"{x['test']['fpr']:.3f} [{c['fpr'][0]:.3f}, {c['fpr'][1]:.3f}] | {x['test']['recall']:.3f} | {x['test']['precision']:.3f} | "
                     f"{x['indirect_val']['recall']:.3f} / {x['indirect_val']['fpr']:.3f} | {x['indirect_test']['recall']:.3f} / {x['indirect_test']['fpr']:.3f} | "
                     f"{x['tricky']['_overall'][0]} ({x['tricky']['hidden_injection_document'][0]}) | {x['xstest_fp']} |")
    L += ["", "## Policy outcome on the test set (allow / warn / block share)\n", "| model | benign allow | benign warn | benign block | attack allow | attack warn | attack block |", "|---|---|---|---|---|---|---|"]
    for name, r in report.items():
        t = r["policy_three_way_test"]
        L.append(f"| {name} | {t['benign']['allow']:.3f} | {t['benign']['warn']:.3f} | {t['benign']['block']:.3f} | {t['attack']['allow']:.3f} | {t['attack']['warn']:.3f} | {t['attack']['block']:.3f} |")
    (RES / "served_thresholds.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote served_thresholds.json / .md")


if __name__ == "__main__":
    main()
