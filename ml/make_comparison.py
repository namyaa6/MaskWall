"""Build ml/results/comparison.md: all baselines and fine-tuned transformers in one place.

Reads ml/results/metrics.json (baselines, run locally) and ml/results/metrics_transformers.json (Colab).
Cleaned labels, with and without indirect-injection augmentation. Nothing is recomputed: every number comes from the
two metrics files, produced with val-only selection and frozen thresholds. Run: python ml/make_comparison.py
"""
import json
from pathlib import Path

RESULTS = Path(__file__).parent / "results"
CATS = ["hidden_injection_document", "benign_document", "benign_mentions_instructions", "benign_suspicious",
        "sneaky_attack", "short_attack", "hinglish", "long_benign"]
# (display name, kind, key in its metrics file)
MODELS = [
    ("length only (LR)", "baseline", "length_lr"),
    ("word TF-IDF (LR)", "baseline", "word_tfidf"),
    ("word+char TF-IDF (LR)", "baseline", "wordchar"),
    ("MiniLM frozen emb (LR)", "baseline", "minilm_emb"),
    ("MiniLM fine-tuned", "transformer", "minilm"),
    ("DeBERTa-v3-small fine-tuned", "transformer", "deberta_v3_small"),
]
TRAIN = [("plain", "cleaned"), ("+aug", "cleaned_aug")]


def load():
    base = json.loads((RESULTS / "metrics.json").read_text())["baselines"]
    tr = json.loads((RESULTS / "metrics_transformers.json").read_text())["transformers"]
    return base, tr


def get(base, tr, kind, key, variant):
    return (base if kind == "baseline" else tr)[variant][key]


def ci(c):
    return f"[{c[0]:.3f}, {c[1]:.3f}]"


def main():
    base, tr = load()
    L = ["# Comparison: baselines and fine-tuned transformers (generated by ml/make_comparison.py)\n",
         "Cleaned labels. `plain` = trained on `train.parquet`; `+aug` = trained on `train_augmented.parquet` (train + 800 synthetic "
         "indirect-injection rows). C / epoch and the decision threshold were chosen on val only; test, indirect_eval, tricky and xstest "
         "were scored once with those frozen choices. Brackets are bootstrap 95% CIs over rows (1,000 resamples, seed 42). "
         "Baselines ran locally (sklearn); transformers ran on a Colab T4 (`ml/train_transformer.ipynb`, one seed, so seed-to-seed variance is unmeasured).\n",
         "## 1. Main table\n",
         "| model | train | val F1 (thr) | test F1 [CI] | test FPR [CI] | test recall | test precision | indirect_eval F1 [CI] | indirect recall | indirect FPR | tricky /49 | xstest FP /250 |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, kind, key in MODELS:
        for tag, variant in TRAIN:
            r = get(base, tr, kind, key, variant)
            t, ie = r["test"], r["indirect_eval"]
            L.append(f"| {name} | {tag} | {r['val']['f1']:.3f} ({r['threshold']:.3f}) | {t['f1']:.3f} {ci(t['ci95']['f1'])} | "
                     f"{t['fpr']:.3f} {ci(t['ci95']['fpr'])} | {t['recall']:.3f} | {t['precision']:.3f} | "
                     f"{ie['f1']:.3f} {ci(ie['ci95']['f1'])} | {ie['recall']:.3f} | {ie['fpr']:.3f} | "
                     f"{r['tricky']['_overall']['correct']} | {r['xstest_safe']['false_positives']} |")
    L += ["", "indirect_eval is partly in-distribution (built like the augmentation; see docs/decisions.md Day 1.7), so read it as an "
          "upper bound on indirect-injection generalisation. The length-only model flags every indirect_eval row (all passages are long); ignore it there.\n",
          "## 2. Tricky set per category (correct/total)\n",
          "| model | train | " + " | ".join(c.replace("_", " ") for c in CATS) + " |", "|---|---|" + "---|" * len(CATS)]
    for name, kind, key in MODELS:
        for tag, variant in TRAIN:
            tk = get(base, tr, kind, key, variant)["tricky"]
            L.append(f"| {name} | {tag} | " + " | ".join(f"{tk[c]['correct']}/{tk[c]['total']}" for c in CATS) + " |")
    L += ["", "Category sizes are 5-11 rows, so one row is 9-20 points; a 1-2 row swing is noise. `hidden injection document` and "
          "`sneaky attack` / `short attack` contain attacks; `benign *`, `hinglish` (benign half) and `long benign` contain benign rows "
          "(hinglish has 6 benign + 5 attacks).\n",
          "## 3. Operating-point check: test recall at the val-tuned FPR <= 1% threshold (reporting only)\n",
          "| model | train | recall | test FPR at that threshold |", "|---|---|---|---|"]
    for name, kind, key in MODELS:
        for tag, variant in TRAIN:
            a = get(base, tr, kind, key, variant)["test"]["at_val_fpr_1pct"]
            L.append(f"| {name} | {tag} | {a['recall']:.3f} | {a['fpr']:.3f} |")
    L += ["", "## 4. Indirect_eval recall split by insertion style (shortcut check)\n",
          "| model | train | attacks caught bare | attacks caught annotated | benign flagged bare | benign flagged annotated |", "|---|---|---|---|---|---|"]
    for name, kind, key in MODELS[1:]:
        for tag, variant in TRAIN:
            b = get(base, tr, kind, key, variant)["indirect_eval"]["by_annotation"]
            f = lambda k: f"{b[k]['flagged']}/{b[k]['n']}"
            L.append(f"| {name} | {tag} | {f('label1_bare')} | {f('label1_annotated')} | {f('label0_bare')} | {f('label0_annotated')} |")
    L += ["", "## 5. Training details for the transformers (from the notebook run)\n", "| model | train | best epoch | val threshold | minutes |", "|---|---|---|---|---|"]
    for name, kind, key in MODELS[4:]:
        for tag, variant in TRAIN:
            r = get(base, tr, kind, key, variant)
            L.append(f"| {name} | {tag} | {r['best_epoch']} | {r['threshold']:.3f} | {r['train_seconds'] / 60:.1f} |")
    (RESULTS / "comparison.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", RESULTS / "comparison.md")


if __name__ == "__main__":
    main()
